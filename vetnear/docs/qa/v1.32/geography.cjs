const { chromium } = require('/opt/codex/cua_node/lib/node_modules/playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const results=[];
 for (const width of [390,1440]) {
  console.log('Starting viewport', width);
  const context = await browser.newContext({viewport:{width,height:width===390?844:1000}});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:3001/nearby?region=kyiv_oblast',{waitUntil:'load'});
  await page.getByRole('button',{name:'Київська область',exact:true}).waitFor();
  assert.equal(await page.locator('.distance-pill').count(),0,'No fictional distance without location');
  assert.equal(await page.getByLabel('Район',{exact:true}).count(),0,'Oblast has no Kyiv district control');
  const countText = await page.locator('p[role=status]').filter({hasText:'Знайдено'}).innerText();
  assert.match(countText,/Знайдено:\s*[1-9]/);
  await page.getByLabel('Населений пункт').selectOption({label:'Біла Церква'});
  await page.waitForFunction(() => { const cards=Array.from(document.querySelectorAll('.place-card')); return cards.length>0 && cards.every(c=>c.textContent.includes('Біла Церква')); });
  const selectedCards=await page.locator('.place-card').allTextContents();
  assert.ok(selectedCards.length>0);
  assert.ok(selectedCards.every(t=>t.includes('Біла Церква')));
  assert.equal(await page.locator('.distance-pill').count(),0);
  await page.screenshot({path:`/workspace/work/screenshots-v132/region-search${width===390?'':'-desktop'}.png`,fullPage:true});
  await page.getByRole('button',{name:'Карта',exact:true}).click();
  await page.locator('.leaflet-container').waitFor();
  await page.locator('.leaflet-container').scrollIntoViewIfNeeded();
  await page.waitForTimeout(700);
  const mapCheck=await page.locator('.leaflet-container').evaluate(el=>{
   const b=el.getBoundingClientRect();
   const pins=Array.from(el.querySelectorAll('.vetnear-pin')).map(p=>{const r=p.getBoundingClientRect(); return {x:r.x,y:r.y,w:r.width,h:r.height,inside:r.x>=b.x-1&&r.right<=b.right+1&&r.y>=b.y-1&&r.bottom<=b.bottom+1};});
   return {bounds:{x:b.x,y:b.y,width:b.width,height:b.height},pins,userPins:el.querySelectorAll('.vetnear-user').length};
  });
  assert.equal(mapCheck.userPins,0);
  assert.equal(mapCheck.pins.length,selectedCards.length);
  assert.ok(mapCheck.pins.every(p=>p.inside),'All Bila Tserkva map pins are inside visible map bounds');
  await page.screenshot({path:`/workspace/work/screenshots-v132/region-map-${width}.png`});
  console.log('Oblast/locality/map passed', width);
  await page.goto('http://127.0.0.1:3001/nearby?district=pozniaky',{waitUntil:'load'});
  assert.equal(await page.getByRole('button',{name:'Київ',exact:true}).getAttribute('aria-pressed'),'true');
  assert.equal(await page.getByLabel('Район',{exact:true}).inputValue(),'darnytskyi');
  await page.getByRole('button',{name:'Київська область',exact:true}).click();
  await page.getByLabel('Район',{exact:true}).waitFor({state:'detached'});
  assert.equal(await page.getByLabel('Район',{exact:true}).count(),0);
  const resetCount = await page.locator('p[role=status]').filter({hasText:'Знайдено'}).innerText();
  assert.match(resetCount,/Знайдено:\s*[1-9]/);
  await page.getByRole('button',{name:'Київ',exact:true}).click();
  await page.getByLabel('Район',{exact:true}).waitFor({state:'attached'});
  assert.equal(await page.getByLabel('Район',{exact:true}).inputValue(),'all');
  console.log('Legacy district/reset passed', width);
  await page.evaluate(() => sessionStorage.setItem('vetnear:coords', JSON.stringify({coords:{latitude:50.4501,longitude:30.5234},savedAt:Date.now()})));
  await page.goto('http://127.0.0.1:3001/nearby?region=kyiv_oblast&locality=%D0%91%D1%96%D0%BB%D0%B0%20%D0%A6%D0%B5%D1%80%D0%BA%D0%B2%D0%B0&category=veterinary_clinic&animal=bird&radius=100000',{waitUntil:'load'});
  await page.getByRole('searchbox',{name:'Назва закладу або адреса'}).fill('Айболит');
  await page.getByRole('button',{name:'Показати заклади для уточнення',exact:true}).waitFor();
  assert.equal(await page.locator('.place-card').count(),0);
  assert.match(await page.locator('main').innerText(),/Це не означає, що допомоги немає/);
  await page.getByRole('button',{name:'Показати заклади для уточнення',exact:true}).click();
  await page.waitForFunction(() => document.querySelectorAll('.place-card').length >= 2);
  assert.equal(await page.getByLabel('Населений пункт').inputValue(),'Біла Церква');
  assert.equal(await page.locator('#nearby-advanced-filters').getByLabel('Категорія',{exact:true}).inputValue(),'veterinary_clinic');
  assert.equal(await page.getByLabel('Тварина',{exact:true}).inputValue(),'all');
  assert.equal(await page.getByRole('searchbox',{name:'Назва закладу або адреса'}).inputValue(),'Айболит');
  assert.equal(await page.getByRole('button',{name:'Київська область',exact:true}).getAttribute('aria-pressed'),'true');
  assert.match(await page.locator('.discovery-location').innerText(),/Пошук від обраної точки/);
  assert.ok(await page.locator('.distance-pill').count()>0);
  assert.ok((await page.locator('.place-card').allTextContents()).every(t=>t.includes('Айболит')));
  console.log('Species recovery passed', width);
  await page.goto('http://127.0.0.1:3001/add-place',{waitUntil:'load'});
  await page.getByLabel('Назва закладу').fill('Тест географії — не надсилати');
  await page.getByLabel('Адреса',{exact:false}).fill('вул. Тестова, 1');
  await page.getByLabel('Телефон',{exact:false}).fill('+380441234567');
  await page.getByLabel('Територія',{exact:true}).selectOption('kyiv_oblast');
  assert.equal(await page.locator('#district').count(),0);
  await page.getByRole('button',{name:'Продовжити',exact:true}).click();
  assert.match(await page.getByRole('alert').filter({hasText:'населений пункт'}).innerText(),/населений пункт/);
  await page.getByLabel('Населений пункт').fill('Федорівка');
  await page.getByRole('button',{name:'Продовжити',exact:true}).click();
  await page.locator('#services').waitFor({state:'visible'});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
  assert.equal(overflow,false,'No page horizontal overflow');
  assert.deepEqual(errors,[],'No page errors');
  results.push({width,oblastCatalogue:countText,bilaTserkvaCards:selectedCards.length,mapFit:mapCheck.pins.every(p=>p.inside),noInventedOrigin:true,legacyDistrict:'pozniaky → darnytskyi',districtReset:true,oblastFormRequiredLocality:true,formProgresses:true,speciesRecoveryPreservesRegionLocalityCategoryQueryOrigin:true,horizontalOverflow:overflow,pageErrors:errors});
  await context.close();
 }
 await browser.close();
 fs.writeFileSync('/workspace/work/geo-qa-v132-results.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify(results,null,2));
})().catch(e=>{console.error(e);process.exit(1);});
